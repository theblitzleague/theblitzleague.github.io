#!/usr/bin/env python3
"""Turn us-atlas states-albers-10m.json (TopoJSON, already projected with d3.geoAlbersUsa at scale 1300,
translate [487.5, 305]) into js/us-map.js: SVG path strings the map page draws directly.
Source: https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-albers-10m.json
Usage: python3 tools/build_map.py states-albers-10m.json"""
import json, sys, os
t = json.load(open(sys.argv[1]))
sx, sy = t["transform"]["scale"]; tx, ty = t["transform"]["translate"]
arcs = []
for arc in t["arcs"]:
    x = y = 0; pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((round(x * sx + tx, 1), round(y * sy + ty, 1)))
    arcs.append(pts)
def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return "M" + "L".join(f"{x:g},{y:g}" for x, y in pts) + "Z"
def path(g):
    polys = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"]
    return "".join(ring(r) for poly in polys for r in poly)
states = [{"id": g["id"], "name": g["properties"]["name"], "d": path(g)} for g in t["objects"]["states"]["geometries"]]
nation = "".join(path(g) for g in t["objects"]["nation"]["geometries"])
out = os.path.join(os.path.dirname(__file__), "..", "js", "us-map.js")
with open(out, "w") as f:
    f.write("/* US states, pre-projected (d3.geoAlbersUsa, scale 1300, translate 487.5,305) from us-atlas@3.0.1. Generated by tools/build_map.py. */\n")
    f.write("window.US_MAP = " + json.dumps({"viewBox": "0 0 975 610", "states": states, "nation": nation}, separators=(",", ":")) + ";\n")
print(len(states), "states,", os.path.getsize(out), "bytes")
